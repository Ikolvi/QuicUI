import 'dart:io';
import 'package:quicui_linker/quicui_linker.dart';

void main(List<String> args) async {
  if (args.length < 3) {
    print('QuicUI Differential AOT Linker');
    print('');
    print('Usage: dart link.dart <baseline> <patch.aot> <output.vmcode>');
    print('');
    print('Arguments:');
    print('  baseline     Mach-O file (iOS App) or ELF file (Android libapp.so)');
    print('  patch.aot    ELF file generated by gen_snapshot');
    print('  output.vmcode Output differential patch file');
    print('');
    print('Options:');
    print('  --analyze    Print detailed analysis of the patch');
    print('  --no-link    Skip link info generation (faster but less efficient patches)');
    exit(1);
  }

  final baselineFile = File(args[0]);
  final patchFile = File(args[1]);
  final outputFile = File(args[2]);
  final analyze = args.contains('--analyze');
  final skipLink = args.contains('--no-link');

  if (!await baselineFile.exists()) {
    print('Error: Baseline file not found: ${baselineFile.path}');
    exit(1);
  }

  if (!await patchFile.exists()) {
    print('Error: Patch file not found: ${patchFile.path}');
    exit(1);
  }

  print('QuicUI Differential AOT Linker v2.0');
  print('=' * 50);
  print('Baseline: ${baselineFile.path}');
  print('Patch:    ${patchFile.path}');
  print('Output:   ${outputFile.path}');
  print('');

  try {
    // Step 1: Parse files (detect format automatically)
    print('Step 1: Parsing baseline and patch files...');

    // Try to parse as Mach-O first (iOS)
    MachoFile? machoBaseline;
    ElfFile? elfBaseline;

    try {
      machoBaseline = await parseMachoFile(baselineFile);
      print('✅ Detected Mach-O baseline (iOS)');
    } catch (e) {
      // Try ELF (Android)
      try {
        elfBaseline = await parseElfFile(baselineFile);
        print('✅ Detected ELF baseline (Android)');
      } catch (e2) {
        throw Exception('Could not parse baseline as Mach-O or ELF: $e');
      }
    }

    final patch = await parseElfFile(patchFile);
    print('✅ Parsed patch ELF');

    // Step 2: Analyze differences
    print('\nStep 2: Analyzing snapshot differences...');
    final SnapshotAnalyzer analyzer;
    if (machoBaseline != null) {
      analyzer = SnapshotAnalyzer.fromMacho(machoBaseline, patch);
    } else {
      analyzer = SnapshotAnalyzer.fromElf(elfBaseline!, patch);
    }
    final diff = await analyzer.analyze();

    // Step 3: Generate differential patch with link info
    print('\nStep 3: Generating differential patch...');
    final DifferentialLinker linker;
    if (machoBaseline != null) {
      linker = DifferentialLinker.forIOS(
        baseline: machoBaseline,
        patch: patch,
        diff: diff,
      );
    } else {
      linker = DifferentialLinker.forAndroid(
        baseline: elfBaseline!,
        patch: patch,
        diff: diff,
      );
    }

    final patchElf = await linker.generatePatch();

    // Generate link info (unless skipped)
    LinkInfo? linkInfo;
    if (!skipLink) {
      linkInfo = linker.generateLinkInfo();
    } else {
      print('Skipping link info generation (--no-link)');
    }

    // Optional: Print detailed analysis
    if (analyze) {
      linker.analyzeElf();
      print('\nPatch Summary:');
      final summary = linker.getSummary();
      summary.forEach((key, value) {
        print('  $key: $value');
      });
    }

    // Step 4: Create .vmcode file with header
    print('\nStep 4: Creating .vmcode file...');
    final generator = VmcodeGenerator();
    await generator.generate(
      patchElf: patchElf,
      outputFile: outputFile,
      linkInfo: linkInfo,
    );

    print('\n✅ Success!');
    print('Differential patch created: ${outputFile.path}');
    print('Size: ${await outputFile.length()} bytes');

    // Verify the output
    print('\nVerifying output...');
    final header = await VmcodeGenerator.readHeader(outputFile);
    print('Header validation: ${header.isValid ? "✅ VALID" : "❌ INVALID"}');
    if (header.hasLinkInfo) {
      print('Link info: ${header.linkInfoSize} bytes');
    }
  } catch (e, stack) {
    print('\n❌ Error: $e');
    print(stack);
    exit(1);
  }
}
